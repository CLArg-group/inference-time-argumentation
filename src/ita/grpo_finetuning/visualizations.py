from pathlib import Path

import matplotlib
matplotlib.use("Agg")   

import matplotlib.pyplot as plt

from ita.grpo_finetuning.training_store import TrainingStore


def _save_plot(xs, ys, xlabel, ylabel, title, path, extra_series: dict = None):
    """Generic helper: one primary series + optional dict of extra series."""
    fig, ax = plt.subplots(figsize=(10, 5))
    ax.plot(xs, ys, label=ylabel, linewidth=1.2)
    if extra_series:
        for label, (exs, eys) in extra_series.items():
            ax.plot(exs, eys, label=label, linewidth=1.2, linestyle="--")
    ax.set_xlabel(xlabel)
    ax.set_ylabel(ylabel)
    ax.set_title(title)
    ax.legend()
    ax.grid(True, alpha=0.3)
    plt.tight_layout()
    plt.savefig(path, dpi=150)
    plt.close(fig)


def plot_loss(store: TrainingStore, plots_dir: Path):
    """Loss vs training steps."""
    _, loss_history, _ = store.snapshot()
    if not loss_history:
        return
    xs = [e["step"] for e in loss_history]
    ys = [e["loss"] for e in loss_history]
    _save_plot(
        xs, ys,
        xlabel="Step", ylabel="Loss",
        title="Training Loss vs Steps",
        path=plots_dir / "loss_vs_steps.png",
    )


def plot_claim_strength(store: TrainingStore, plots_dir: Path):
    """Predicted claim strength vs training steps (successful completions only)."""
    records, _, _ = store.snapshot()
    valid = [r for r in records if r.failure_mode is None]
    if not valid:
        return
    xs = [r.step for r in valid]
    ys = [r.predicted_strength for r in valid]
    _save_plot(
        xs, ys,
        xlabel="Step", ylabel="Claim Strength",
        title="Predicted Claim Strength vs Steps",
        path=plots_dir / "claim_strength_vs_steps.png",
    )


def plot_arg_counts(store: TrainingStore, plots_dir: Path):
    """Number of supporters and attackers generated per claim vs steps."""
    records, _, _ = store.snapshot()
    valid = [r for r in records if r.failure_mode is None]
    if not valid:
        return
    xs = [r.step for r in valid]
    supporters = [r.num_supporters for r in valid]
    attackers = [r.num_attackers for r in valid]

    fig, ax = plt.subplots(figsize=(10, 5))
    ax.plot(xs, supporters, label="Supporters", linewidth=1.2, color="steelblue")
    ax.plot(xs, attackers,  label="Attackers",  linewidth=1.2, color="darkorange", linestyle="--")
    ax.set_xlabel("Step")
    ax.set_ylabel("Count")
    ax.set_title("Supporters & Attackers per Claim vs Steps")
    ax.legend()
    ax.grid(True, alpha=0.3)
    plt.tight_layout()
    plt.savefig(plots_dir / "arg_counts_vs_steps.png", dpi=150)
    plt.close(fig)


def plot_thinking_tokens(store: TrainingStore, plots_dir: Path):
    """Total thinking tokens generated by the model vs steps."""
    records, _, _ = store.snapshot()
    if not records:
        return
    xs = [r.step for r in records]
    ys = [r.thinking_tokens for r in records]
    _save_plot(
        xs, ys,
        xlabel="Step", ylabel="Thinking Tokens",
        title="Thinking Tokens Generated vs Steps",
        path=plots_dir / "thinking_tokens_vs_steps.png",
    )


def plot_thresholds(store: TrainingStore, plots_dir: Path):
    """Re-optimized upper/lower reward thresholds vs steps.

    No-op when threshold optimization was never enabled (threshold_history
    stays empty), matching the other plot_* functions' empty-data behaviour.
    """
    history = store.snapshot_thresholds()
    if not history:
        return
    xs = [r.step for r in history]
    upper = [r.upper for r in history]
    lower = [r.lower for r in history]

    fig, ax = plt.subplots(figsize=(10, 5))
    ax.step(xs, upper, where="post", label="Upper threshold", linewidth=1.2, color="steelblue")
    ax.step(xs, lower, where="post", label="Lower threshold", linewidth=1.2, color="darkorange", linestyle="--")
    ax.set_xlabel("Step")
    ax.set_ylabel("Threshold value")
    ax.set_title("Re-optimized Reward Thresholds vs Steps")
    ax.legend()
    ax.grid(True, alpha=0.3)
    plt.tight_layout()
    plt.savefig(plots_dir / "thresholds_vs_steps.png", dpi=150)
    plt.close(fig)


def plot_failure_modes(store: TrainingStore, plots_dir: Path):
    """Bar chart of generation failure mode counts."""
    _, _, failure_counts = store.snapshot()
    if not failure_counts:
        return
    fig, ax = plt.subplots(figsize=(8, 4))
    ax.bar(list(failure_counts.keys()), list(failure_counts.values()), color="salmon")
    ax.set_xlabel("Failure Mode")
    ax.set_ylabel("Count")
    ax.set_title("Generation Failure Modes")
    plt.xticks(rotation=15, ha="right")
    plt.tight_layout()
    plt.savefig(plots_dir / "failure_modes.png", dpi=150)
    plt.close(fig)


def generate_all_plots(store: TrainingStore, plots_dir: Path):
    """Convenience wrapper – regenerates every plot in one call."""
    plots_dir.mkdir(parents=True, exist_ok=True)
    plot_loss(store, plots_dir)
    plot_claim_strength(store, plots_dir)
    plot_arg_counts(store, plots_dir)
    plot_thinking_tokens(store, plots_dir)
    plot_thresholds(store, plots_dir)
    plot_failure_modes(store, plots_dir)